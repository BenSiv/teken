-- The container target: a generation is an image, teken/<env>:<id>,
-- built by podman from a Containerfile teken generates. Inside the
-- image the generation lives at /opt/teken (bin/ on PATH, files/, ...)
-- laid out as in the home target, so the same units serve both.
-- Build steps run inside the image build, against the image's own
-- libraries; their trees stay at /opt/teken-build/<step>.
--
-- Activation swaps containers: the new one is created as <name>-next,
-- the old one is stopped and renamed to <name>-<from id>, the new one
-- takes the name and starts. Rollback undoes those renames; commit
-- removes the old container. State lives on the volumes and bind mounts
-- the env declares, which both containers share, so nothing in the old
-- container's own layer is needed after the swap -- and teken refuses
-- the swap when that layer holds changes outside declared state.

lfs = require("lfs")
data = require("data")
shell = require("shell")
store = require("store")
lock = require("lock")
sources = require("sources")
version = require("version")

container = {}

ROOT = "/opt/teken"
BUILD = "/opt/teken-build"

-- Paths a container may change in its own layer without that being
-- lost work.
SCRATCH = {"/tmp", "/run", "/var/tmp", "/var/cache", "/var/log", "/dev", "/proc", "/sys",
    "/etc/hostname", "/etc/hosts", "/etc/resolv.conf"}

function container.tag(name, id)
    return "teken/" .. name .. ":" .. id
end

function podman(args, what)
    return shell.must("podman " .. args, what)
end

function exists(name)
    return shell.ok("podman container exists " .. shell.quote(name))
end

-- The generation a container was created from, by its image's label.
function generation_of(name)
    out = podman("inspect --format '{{index .Config.Labels \"teken.id\"}}' " .. shell.quote(name), "podman inspect " .. name)
    return shell.trim(out)
end

function json_string(text)
    text = string.gsub(text, "\\", "\\\\")
    text = string.gsub(text, "\"", "\\\"")
    text = string.gsub(text, "\n", "\\n")
    text = string.gsub(text, "\t", "\\t")
    return "\"" .. text .. "\""
end

-- An ENV value: double-quoted, with $ escaped so podman does not
-- substitute it at build time.
function env_value(text)
    return (string.gsub(json_string(text), "%$", "\\$"))
end

function copy_line(from, to)
    return "COPY [" .. json_string(from) .. ", " .. json_string(to) .. "]"
end

function expand_build_refs(text)
    return (string.gsub(text, "%${build%.([%w_]+)}", function(name)
        return BUILD .. "/" .. name
    end))
end

function step_script(step)
    lines = {"cd " .. shell.quote(BUILD .. "/" .. step.name)}
    if step.env != nil then
        for _, name in ipairs(data.sorted_keys(step.env)) do
            table.insert(lines, "export " .. name .. "=" .. shell.quote(expand_build_refs(step.env[name])))
        end
    end
    table.insert(lines, expand_build_refs(step.cmd))
    return table.concat(lines, "\n") .. "\n"
end

-- The Containerfile for generation `id`. It reads only the build
-- context assemble_context lays out: sources/<step>, steps/<step>.sh,
-- fetch/<sha256>, files/<path>.
function container.containerfile(env, pins, id)
    c = env.container
    lines = {
        "# Generated by teken: env " .. env.name .. ", generation " .. id .. ". Edits are lost on the next build.",
        "FROM " .. c.base .. "@" .. pins.images[c.base],
    }
    if #env.apt > 0 then
        packages = {}
        for _, package in ipairs(env.apt) do
            table.insert(packages, shell.quote(package))
        end
        table.insert(lines, "RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "
            .. table.concat(packages, " ") .. " && rm -rf /var/lib/apt/lists/*")
    end
    table.insert(lines, "RUN mkdir -p " .. ROOT .. "/bin")
    for _, step in ipairs(env.build) do
        table.insert(lines, copy_line("sources/" .. step.name, BUILD .. "/" .. step.name))
        table.insert(lines, copy_line("steps/" .. step.name .. ".sh", BUILD .. "/" .. step.name .. ".sh"))
        table.insert(lines, "RUN sh " .. BUILD .. "/" .. step.name .. ".sh")
        for _, from in ipairs(data.sorted_keys(step.install)) do
            dest = ROOT .. "/" .. step.install[from]
            table.insert(lines, "RUN mkdir -p " .. shell.quote(shell.parent(dest)) .. " && cp -a "
                .. shell.quote(BUILD .. "/" .. step.name .. "/" .. from) .. " " .. shell.quote(dest))
        end
    end
    for _, item in ipairs(env.fetch) do
        table.insert(lines, copy_line("fetch/" .. pins.fetch[item.url], ROOT .. "/" .. item.path))
        if item.mode != nil then
            table.insert(lines, "RUN chmod " .. shell.quote(item.mode) .. " " .. shell.quote(ROOT .. "/" .. item.path))
        end
    end
    for _, item in ipairs(env.files) do
        table.insert(lines, copy_line("files/" .. item.path, ROOT .. "/" .. item.path))
        if item.mode != nil then
            table.insert(lines, "RUN chmod " .. shell.quote(item.mode) .. " " .. shell.quote(ROOT .. "/" .. item.path))
        end
    end
    for _, item in ipairs(env.links) do
        table.insert(lines, "RUN mkdir -p " .. shell.quote(shell.parent(item.path)) .. " && rm -rf "
            .. shell.quote(item.path) .. " && ln -s " .. shell.quote(ROOT .. "/" .. item.target) .. " " .. shell.quote(item.path))
    end
    table.insert(lines, "ENV PATH=" .. ROOT .. "/bin:${PATH}")
    for _, name in ipairs(data.sorted_keys(env.env)) do
        table.insert(lines, "ENV " .. name .. "=" .. env_value(env.env[name]))
    end
    table.insert(lines, "LABEL teken.env=" .. json_string(env.name) .. " teken.id=" .. json_string(id))
    return table.concat(lines, "\n") .. "\n"
end

-- A link target must be something the generation contains: a path an
-- install, fetch or file puts there, or a path inside one of those.
function check_link_targets(env)
    paths = {}
    for _, step in ipairs(env.build) do
        for _, to in pairs(step.install) do
            table.insert(paths, to)
        end
    end
    for _, item in ipairs(env.fetch) do
        table.insert(paths, item.path)
    end
    for _, item in ipairs(env.files) do
        table.insert(paths, item.path)
    end
    for _, link in ipairs(env.links) do
        found = false
        for _, path in ipairs(paths) do
            if link.target == path or string.sub(link.target, 1, string.len(path) + 1) == path .. "/" then
                found = true
            end
        end
        if found == false then
            error(link.where .. ": link target " .. link.target .. " is not in the generation", 0)
        end
    end
end

function assemble_context(env, pins, ctx)
    check_link_targets(env)
    for _, step in ipairs(env.build) do
        sources.checkout(step.from, env.sources[step.from], pins.sources[step.from].commit, ctx .. "/sources/" .. step.name)
        shell.mkdir(ctx .. "/steps")
        data.write_file(ctx .. "/steps/" .. step.name .. ".sh", step_script(step))
    end
    for _, item in ipairs(env.fetch) do
        digest = pins.fetch[item.url]
        cached = store.cache_dir("fetch") .. "/" .. digest
        if lfs.attributes(cached) == nil then
            if lock.download(item.url) != digest then
                error(item.where .. ": " .. item.url .. " changed since it was pinned; run tkn update", 0)
            end
        end
        shell.mkdir(ctx .. "/fetch")
        shell.must("cp " .. shell.quote(cached) .. " " .. shell.quote(ctx .. "/fetch/" .. digest), "copy " .. item.url)
    end
    for _, item in ipairs(env.files) do
        dest = ctx .. "/files/" .. item.path
        shell.mkdir(shell.parent(dest))
        if item.source != nil then
            shell.must("cp -a " .. shell.quote(env.spec_dir .. "/" .. item.source) .. " " .. shell.quote(dest), "copy " .. item.source)
        else
            data.write_file(dest, item.content)
        end
    end
end

function verify_prefix()
    return "-e TEKEN_GEN=" .. ROOT .. " "
end

-- Runs each verify command in a throwaway container of `tag`, with no
-- state mounted, so a candidate never touches live data.
function verify_image(env, tag)
    for _, cmd in ipairs(env.verify) do
        print("  ? " .. cmd)
        if shell.run("podman run --rm --entrypoint sh " .. verify_prefix() .. shell.quote(tag) .. " -c " .. shell.quote(cmd)) != true then
            return cmd
        end
    end
    return nil
end

function container.has_gen(name, id)
    return store.has_gen(name, id) and shell.ok("podman image exists " .. shell.quote(container.tag(name, id)))
end

-- Builds the image for generation `id` and verifies it. gens/<id>/
-- (the Containerfile and meta.lua) appears only once both succeeded.
function container.build(env, pins, id)
    tag = container.tag(env.name, id)
    if container.has_gen(env.name, id) then
        print("generation " .. id .. " is already built")
        return
    end
    final = store.gen_path(env.name, id)
    tmp = final .. ".tmp"
    shell.remove(tmp)
    shell.mkdir(tmp .. "/context")
    ok, err = pcall(assemble_context, env, pins, tmp .. "/context")
    if ok != true then
        shell.remove(tmp)
        error(err, 0)
    end
    data.write_file(tmp .. "/Containerfile", container.containerfile(env, pins, id))
    print("building image " .. tag)
    if shell.run("podman build --tag " .. shell.quote(tag) .. " --file " .. shell.quote(tmp .. "/Containerfile")
            .. " " .. shell.quote(tmp .. "/context")) != true then
        shell.remove(tmp)
        error("podman build of " .. tag .. " failed", 0)
    end
    shell.remove(tmp .. "/context")
    print("verifying")
    failed = verify_image(env, tag)
    if failed != nil then
        error("verify failed: " .. failed .. "\nthe image is kept as " .. tag .. " (podman rmi it when done)", 0)
    end
    data.save(tmp .. "/meta.lua", {
        id = id, env = env.name, target = "container", teken = version.number, image = tag,
        created = os.date("!%Y-%m-%dT%H:%M:%SZ"), steps = {},
        container = env.container, state = env.state, verify = env.verify,
    })
    ok, err = os.rename(tmp, final)
    if ok == nil then
        error("cannot finish " .. final .. ": " .. tostring(err), 0)
    end
end

function inside(path, dir)
    return path == dir or string.sub(path, 1, string.len(dir) + 1) == dir .. "/"
end

-- How generation `id` runs: its container section, state and verify
-- commands as recorded at build time, so activating an older
-- generation (rollback) uses its own name, mounts and checks, not the
-- current spec's.
function run_of(env, id)
    meta = store.meta(env.name, id)
    if meta == nil or meta.container == nil then
        return {container = env.container, state = env.state, verify = env.verify}
    end
    return {container = meta.container, state = meta.state, verify = meta.verify}
end

-- Changes in the running container's own layer that a swap would lose:
-- everything podman diff reports outside declared state, `ephemeral`
-- and SCRATCH, minus directories listed only because something below
-- them changed. `env` needs only `container` and `state`.
function container.undeclared(env, name)
    allowed = {}
    for _, path in ipairs(SCRATCH) do
        table.insert(allowed, path)
    end
    for _, state in ipairs(env.state) do
        table.insert(allowed, state.path)
    end
    if env.container.ephemeral != nil then
        for _, path in ipairs(env.container.ephemeral) do
            table.insert(allowed, path)
        end
    end
    changed = {}
    for _, line in ipairs(shell.lines(podman("diff " .. shell.quote(name), "podman diff " .. name))) do
        path = string.match(line, "^[ACD]%s+(/.*)$")
        if path != nil then
            ok = true
            for _, root in ipairs(allowed) do
                if inside(path, root) then
                    ok = false
                end
            end
            if ok == true then
                table.insert(changed, path)
            end
        end
    end
    result = {}
    for _, path in ipairs(changed) do
        parent_only = false
        for _, other in ipairs(changed) do
            if other != path and inside(other, path) then
                parent_only = true
            end
        end
        for _, root in ipairs(allowed) do
            if root != path and inside(root, path) then
                parent_only = true
            end
        end
        if parent_only == false then
            table.insert(result, path)
        end
    end
    return result
end

function create_args(env_name, run, tag)
    c = run.container
    args = {"--name " .. shell.quote(c.name .. "-next"), "--label teken.env=" .. shell.quote(env_name)}
    if c.hostname != nil then
        table.insert(args, "--hostname " .. shell.quote(c.hostname))
    end
    if c.tty == true then
        table.insert(args, "--tty")
    end
    if c.restart != nil then
        table.insert(args, "--restart " .. shell.quote(c.restart))
    end
    if c.ports != nil then
        for _, port in ipairs(c.ports) do
            table.insert(args, "--publish " .. shell.quote(port))
        end
    end
    for _, state in ipairs(run.state) do
        source = state.volume
        if source == nil then
            source = state.bind
        end
        table.insert(args, "--volume " .. shell.quote(source .. ":" .. state.path))
    end
    table.insert(args, shell.quote(tag))
    if c.command != nil then
        for _, word in ipairs(c.command) do
            table.insert(args, shell.quote(word))
        end
    end
    return table.concat(args, " ")
end

function container.activate(env, from, to, options)
    run = run_of(env, to)
    name = run.container.name
    tag = container.tag(env.name, to)
    old = nil
    old_run = nil
    if from != nil then
        old_run = run_of(env, from)
        old = old_run.container.name
    end
    if exists(name) and name != old then
        error("a container named " .. name .. " exists that teken did not create; rename or remove it first", 0)
    end
    if old != nil and exists(old) and (options == nil or options.discard_undeclared != true) then
        lost = container.undeclared(old_run, old)
        if #lost > 0 then
            error("the running " .. old .. " has changes outside declared state, which the switch would lose:\n  "
                .. table.concat(lost, "\n  ")
                .. "\ndeclare them as state (or container.ephemeral), or pass --discard-undeclared", 0)
        end
    end
    if exists(name .. "-next") then
        podman("rm --force " .. shell.quote(name .. "-next"), "podman rm " .. name .. "-next")
    end
    podman("create " .. create_args(env.name, run, tag), "podman create " .. name .. "-next")
    if old != nil and exists(old) then
        podman("stop " .. shell.quote(old), "podman stop " .. old)
        podman("rename " .. shell.quote(old) .. " " .. shell.quote(old .. "-" .. from), "podman rename " .. old)
    end
    podman("rename " .. shell.quote(name .. "-next") .. " " .. shell.quote(name), "podman rename " .. name .. "-next")
    podman("start " .. shell.quote(name), "podman start " .. name)
    store.set_current(env.name, to)
    print("health check")
    if run.container.health_wait > 0 then
        shell.run("sleep " .. run.container.health_wait)
    end
    running = shell.trim(podman("inspect --format '{{.State.Running}}' " .. shell.quote(name), "podman inspect " .. name))
    if running != "true" then
        error("health check failed: " .. name .. " is not running", 0)
    end
    for _, cmd in ipairs(run.verify) do
        print("  ? " .. cmd)
        if shell.run("podman exec " .. verify_prefix() .. shell.quote(name) .. " sh -c " .. shell.quote(cmd)) != true then
            error("health check failed: " .. cmd, 0)
        end
    end
end

-- Undoes an activation recorded as {from, to}, from any point it
-- reached: the new container gone, the old one back under its name and
-- running.
function container.rollback(env, intent)
    name = run_of(env, intent.to).container.name
    if exists(name .. "-next") then
        podman("rm --force " .. shell.quote(name .. "-next"), "podman rm " .. name .. "-next")
    end
    if exists(name) and generation_of(name) == intent.to then
        podman("rm --force " .. shell.quote(name), "podman rm " .. name)
    end
    if intent.from != nil then
        old = run_of(env, intent.from).container.name
        aside = old .. "-" .. intent.from
        if exists(aside) and exists(old) == false then
            podman("rename " .. shell.quote(aside) .. " " .. shell.quote(old), "podman rename " .. aside)
        end
        if exists(old) then
            podman("start " .. shell.quote(old), "podman start " .. old)
        end
    end
    store.set_current(env.name, intent.from)
end

-- After a successful switch the old container is no longer needed:
-- `tkn rollback` makes a new one from the previous image.
function container.commit(env, from, to)
    if from == nil then
        return
    end
    aside = run_of(env, from).container.name .. "-" .. from
    if exists(aside) then
        podman("rm --force " .. shell.quote(aside), "podman rm " .. aside)
    end
end

function container.remove(name, id)
    shell.ok("podman rmi " .. shell.quote(container.tag(name, id)))
    shell.remove(store.gen_path(name, id))
end

-- For tkn plan: build steps run inside the image build, where podman's
-- layer cache decides what reruns, so all are listed as to build.
function container.steps(env, pins)
    result = {}
    for _, step in ipairs(env.build) do
        table.insert(result, {step = step, cached = false})
    end
    return result
end

-- Links are part of the image, not a set changed on the host.
function container.link_changes(env, from)
    return {}
end

return container
